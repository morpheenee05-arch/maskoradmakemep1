# Request body confirmed from full_capture.har: [3,"Lild6KesPh8l"] — field 1 is
# a client-type enum (3), field 2 the per-page-load client instance id
# (12-char token, generated by the web app and reused across its telemetry).
def sip_register_info_body(client_id: Optional[str] = None) -> str:
    cid = client_id or "".join(
        random.choice("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")
        for _ in range(12)
    )
    return json.dumps([3, cid], separators=(",", ":"))


class GVAuthError(Exception):
    pass


@dataclass
class SipCredentials:
    username: str
    password: str
    domain: str = "web.c.pbx.voice.sip.google.com"
    realm: str = "web.c.pbx.voice.sip.google.com"
    # display number / account identity if the API gives us one
    phone_number: str = ""
    expires_in: int = 3600
    raw: list = field(default_factory=list)
    minted_at: float = field(default_factory=time.time)

    @property
    def uri(self) -> str:
        return f"sip:{self.username}@{self.domain}"

    def stale(self, margin: int = 300) -> bool:
        return time.time() > self.minted_at + max(0, self.expires_in - margin)


def sapisid_hash(cookie_value: str, origin: str = AUTH_ORIGIN, ts: Optional[int] = None) -> str:
    ts = ts or int(time.time())
    digest = hashlib.sha1(f"{ts} {cookie_value} {origin}".encode()).hexdigest()
    return f"{ts}_{digest}"


class VoiceAPIClient:
    """Cookie-authenticated client for the voiceclient protojson API."""

    def __init__(self, cookies: Mapping[str, str], authuser: int = 0,
                 session: Optional[requests.Session] = None):
        self.cookies = dict(cookies)
        self.authuser = authuser
        self.session = session or requests.Session()

    @classmethod
    def from_cookie_header(cls, header: str, **kw) -> "VoiceAPIClient":
        cookies = {}
        for part in header.split(";"):
            if "=" in part:
                k, v = part.split("=", 1)
                cookies[k.strip()] = v.strip()
        return cls(cookies, **kw)

    def _cookie_value(self, name: str) -> str:
        v = self.cookies.get(name)
        if isinstance(v, dict):
            return v.get("value", "")
        return v or ""

    def _authorization(self) -> str:
        parts = []
        for cookie_name, scheme in (
            ("SAPISID", "SAPISIDHASH"),
            ("__Secure-1PAPISID", "SAPISID1PHASH"),
            ("__Secure-3PAPISID", "SAPISID3PHASH"),
        ):
            value = self._cookie_value(cookie_name)
            if value:
                parts.append(f"{scheme} {sapisid_hash(value)}")
        if not parts:
            raise GVAuthError(
                "no SAPISID/__Secure-*PAPISID cookie present — cannot build "
                "Authorization header"
            )
        return " ".join(parts)

    def _headers(self) -> dict:
        # The web client calls this API through the gapi proxy iframe hosted
        # ON clients6.google.com, so Origin/Referer must match that host
        # (XD3 check: "Origin doesn't match Host" otherwise) while the app
        # origin (voice.google.com) travels in X-Origin/X-Referer. The
        # browser also sends the .google.com cookies — SAPISIDHASH alone is
        # not always enough for this endpoint.
        return {
            "Authorization": self._authorization(),
            "Cookie": self._cookie_header(),
            "Content-Type": "application/json+protobuf",
            "Accept": "*/*",
            "Origin": AUTH_ORIGIN,
            "Referer": GAPI_PROXY_REFERER,
            "X-Origin": ORIGIN,
            "X-Referer": ORIGIN,
            "X-Goog-AuthUser": str(self.authuser),
            "X-Requested-With": "XMLHttpRequest",
            "X-JavaScript-User-Agent": "google-api-javascript-client/1.1.0",
            "X-Goog-Encode-Response-If-Executable": "base64",
            "X-Client-Version": "1023720527",
            "User-Agent": USER_AGENT,
        }

    def _cookie_header(self) -> str:
        """Cookies the browser would send to clients6.google.com.

        `self.cookies` may carry per-cookie domain info (CDP harvest) as
        {"NAME": {"value": ..., "domain": ...}} or plain name→value pairs
        (document.cookie harvest — assumed .google.com).
        """
        parts = []
        for name, val in self.cookies.items():
            if isinstance(val, dict):
                domain = (val.get("domain") or "").lstrip(".")
                value = val.get("value", "")
                if domain and not (
                        "clients6.google.com".endswith(domain)
                        or domain.endswith("clients6.google.com")):
                    continue
            else:
                value = val
            parts.append(f"{name}={value}")
        return "; ".join(parts)

    def _post(self, url: str, body: str) -> list:
        resp = self.session.post(
            url, data=body.encode(), headers=self._headers(), timeout=20,
        )
        if resp.status_code != 200:
            raise GVAuthError(f"{url} → HTTP {resp.status_code}: {resp.text[:300]}")
        try:
            return resp.json()
        except json.JSONDecodeError as e:
            raise GVAuthError(f"{url} → non-JSON response: {resp.text[:300]}") from e

    def get_sip_register_info(self, body: Optional[str] = None) -> SipCredentials:
        data = self._post(SIP_REGISTER_INFO_URL, body or sip_register_info_body())
        return parse_sip_credentials(data)

    def get_account(self, body: str = "[]") -> list:
        return self._post(ACCOUNT_GET_URL, body)


# ── response parsing ─────────────────────────────────────────────────────────

def _flatten_strings(node, out):
    if isinstance(node, str):
        out.append(node)
    elif isinstance(node, (list, tuple)):
        for item in node:
            _flatten_strings(item, out)
    elif isinstance(node, dict):
        for item in node.values():
            _flatten_strings(item, out)


def _looks_like_sip_username(s: str) -> bool:
    # capture: "AYpoY9vfVeuZt21oaZU6TdOvDyf2qU8YDPQbKxMQFmEjBsXKz3eOtYI="
    # long base64-ish token, url-safe-ish, ends with '=' or not
    if not (30 <= len(s) <= 80):
        return False
    alphabet = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=_-")
    return all(c in alphabet for c in s)


def parse_sip_credentials(data) -> SipCredentials:
    """Extract username/password from the protojson response.

    Layout proven by the in-page sniff:
        [["1795207594", 287709000], null, null, ["<username>", "<password>"]]
    Field 4 (index 3) is [username, password]. Heuristic walk kept as a
    fallback in case Google rotates the shape.
    """
    try:
        pair = data[3]
        if isinstance(pair, (list, tuple)) and len(pair) >= 2 \
                and isinstance(pair[0], str) and isinstance(pair[1], str) \
                and _looks_like_sip_username(pair[0]):
            return SipCredentials(username=pair[0], password=pair[1], raw=data)
    except (TypeError, IndexError):
        pass

    strings: list[str] = []
    _flatten_strings(data, strings)

    username = next((s for s in strings if _looks_like_sip_username(s)), None)
    password = None
    if username:
        idx = strings.index(username)
        # password is expected near the username in the same message
        for s in strings[idx + 1:] + strings[:idx]:
            if s != username and not s.startswith("sip:") and len(s) >= 6 \
                    and "@" not in s and not s.startswith("http"):
                password = s
                break
    if not username or not password:
        raise GVAuthError(
            "could not parse SIP credentials from sipregisterinfo response; "
            f"strings found: {strings!r}"
        )
    return SipCredentials(username=username, password=password, raw=data)
